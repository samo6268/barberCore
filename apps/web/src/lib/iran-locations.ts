export const IRAN_PROVINCE_NAMES = IRAN_PROVINCES.map((province) => province.name);

export const IRAN_CITIES_BY_PROVINCE: Record<string, IranCity[]> = Object.fromEntries(
  IRAN_PROVINCES.map((province) => [province.name, province.cities]),
);

export const IRAN_CITY_COORDINATES: Record<string, [number, number]> = Object.fromEntries(
  IRAN_PROVINCES.flatMap((province) =>
    province.cities.map((city) => [city.name, [city.latitude, city.longitude] as [number, number]]),
  ),
);

export function getIranCityCoordinates(city: string, province?: string): [number, number] | undefined {
  const provinceCities = province ? IRAN_CITIES_BY_PROVINCE[province] : undefined;
  const match = provinceCities?.find((item) => item.name === city) ??
    IRAN_PROVINCES.flatMap((item) => item.cities).find((item) => item.name === city);
  return match ? [match.latitude, match.longitude] : undefined;
}

export function getIranProvinceForCity(city: string): string | undefined {
  return IRAN_PROVINCES.find((province) => province.cities.some((item) => item.name === city))?.name;
}
